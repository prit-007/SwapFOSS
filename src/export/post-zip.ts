import { buildZip, postSlideJobs, type RenderSlide } from "./engine";
import { introCardHTML, outroCardHTML, toolCardHTML } from "./cards";
import { deepCardHTML } from "./deep-cards";
import { renderCard } from "./render";
import { PRESETS, type PresetKey } from "./presets";
import { generateAllNarratives, generateLinkedInPost } from "./narrative";
import type { Categories, Post, Tool } from "@/types";

export interface PostZipOptions {
  post: Post;
  tools: Tool[];
  categories: Categories;
  presetKey: PresetKey;
  lightTheme: boolean;
  onProgress?: (current: number, total: number, message: string) => void;
}

/** Render every slide of a post and bundle the PNGs into a ZIP blob. */
export async function buildPostZip(
  opts: PostZipOptions,
): Promise<{ blob: Blob; fileCount: number }> {
  const preset = PRESETS[opts.presetKey] ?? PRESETS.linkedin;
  const toolMap = new Map(opts.tools.map((t) => [t.id, t]));
  const jobs = postSlideJobs(opts.post, (id) => toolMap.get(id)?.name ?? id);
  const total = jobs.length;

  const render: RenderSlide = async (slide, job) => {
    const index = jobs.indexOf(job) + 1;
    if (slide.type === "intro") {
      return renderCard(introCardHTML(opts.post, preset, opts.lightTheme, total, opts.tools));
    }
    if (slide.type === "outro") {
      return renderCard(outroCardHTML(opts.post, preset, opts.lightTheme, total));
    }
    const tool = toolMap.get(slide.tool)!;
    const cat = opts.categories[tool.category] ?? { label: tool.category, color: "#888" };
    if (slide.type === "deep") {
      return renderCard(
        deepCardHTML(slide.part, tool, cat, { index, total, preset, light: opts.lightTheme }),
      );
    }
    return renderCard(toolCardHTML(tool, cat, preset, opts.lightTheme, { index, total }));
  };

  const narratives = generateAllNarratives(opts.post, opts.tools);
  const primaryCaption = generateLinkedInPost(opts.post, opts.tools, "story");
  const readme = [
    `# ${opts.post.title}`,
    "",
    "## Included Carousel Slides:",
    ...jobs.map((j) => `- ${j.filename} (${j.label})`),
    "",
    "## Captions & Social Narratives:",
    "- caption.txt: Ready-to-paste primary LinkedIn post narrative",
    "- captions/linkedin-story.txt: Story & pain-point angle",
    "- captions/linkedin-tech.txt: Technical architecture & self-hosting angle",
    "- captions/linkedin-quick.txt: Quick comparison cheat sheet",
    "- captions/twitter-thread.txt: Numbered thread for X / Twitter",
    "- captions/reddit.md: Technical review for Reddit / forums / markdown blogs",
    "- captions/instagram.txt: Mobile carousel caption with slide cues",
    "",
    "Generated by SwapFOSS (https://swapfoss.org)",
  ].join("\n");

  const extraFiles: Record<string, string> = {
    "caption.txt": primaryCaption,
    "README.txt": readme,
    "captions/linkedin-story.txt": narratives["linkedin-story.txt"],
    "captions/linkedin-tech.txt": narratives["linkedin-tech.txt"],
    "captions/linkedin-quick.txt": narratives["linkedin-quick.txt"],
    "captions/twitter-thread.txt": narratives["twitter-thread.txt"],
    "captions/reddit.md": narratives["reddit.md"],
    "captions/instagram.txt": narratives["instagram.txt"],
  };

  return buildZip(jobs, opts.post.id, render, opts.onProgress, extraFiles);
}
